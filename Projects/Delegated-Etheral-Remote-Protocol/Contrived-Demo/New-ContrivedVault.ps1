Write-Host "Vault files created: $vault"
if (-not (Get-Command git -ErrorAction SilentlyContinue)) { Write-Warning 'Git is unavailable; no commit or push.'; return }
& git -C $vault init -b main
if ($LASTEXITCODE -ne 0) { Write-Warning 'Git init failed.'; return }
& git -C $vault add .
if ($LASTEXITCODE -ne 0) { Write-Warning 'Git add failed.'; return }
& git -C $vault -c user.name='Contrived Bootstrap' -c user.email='bootstrap@localhost.invalid' commit -m 'chore: initialize Contrived case study'
if ($LASTEXITCODE -ne 0) { Write-Warning 'Initial commit failed.'; return }
$localSha = (& git -C $vault rev-parse HEAD).Trim()
Write-Host "Initial local commit: $localSha"
if ((Read-Host 'Connect an EXISTING EMPTY GitHub repository? [y/N]') -match '^(y|yes)$') {
  $remote = Read-Host 'Remote HTTPS or SSH URL'
  if (-not [string]::IsNullOrWhiteSpace($remote)) {
    & git -C $vault remote add origin $remote.Trim()
    if ($LASTEXITCODE -ne 0) { Write-Warning 'Could not add remote.'; return }
    if ((Read-Host 'Push initial commit to origin/main? [y/N]') -match '^(y|yes)$') {
      & git -C $vault push -u origin main
      if ($LASTEXITCODE -ne 0) { Write-Warning 'Push failed; local repository is intact.'; return }
      $lookup = & git -C $vault ls-remote origin refs/heads/main
      if ($LASTEXITCODE -ne 0) { Write-Warning 'Remote verification failed.'; return }
      $remoteSha = ($lookup -split '\s+')[0]
      if ($remoteSha -eq $localSha) { Write-Host "Verified remote commit: $remoteSha" }
      if ($remoteSha -ne $localSha) { Write-Warning 'Remote commit differs from local commit.' }
    }
  }
