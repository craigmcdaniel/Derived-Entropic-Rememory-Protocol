# Contrived prototype — creates a NEW Obsidian vault; no changes to existing vaults.
$ErrorActionPreference = 'Stop'
Write-Host 'CONTRIVED — Am I a Big Fat Phoney in the Day and Age of Vibe Coding?'
$defaultParent = Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'Obsidian'
$parent = Read-Host "New vault parent directory [$defaultParent]"
if ([string]::IsNullOrWhiteSpace($parent)) { $parent = $defaultParent }
$name = Read-Host 'New vault name [Contrived-A-Case-Study]'
if ([string]::IsNullOrWhiteSpace($name)) { $name = 'Contrived-A-Case-Study' }
if ($name -match '[\\/:*?"<>|]' -or $name -in @('.','..') -or $name.EndsWith('.') -or $name.EndsWith(' ')) { throw 'Invalid folder name.' }
$vault = Join-Path ([IO.Path]::GetFullPath($parent)) $name
if (Test-Path -LiteralPath $vault) { throw "Target already exists: $vault. Nothing changed." }
Write-Host "New vault: $vault"
if ((Read-Host 'Create this vault? [y/N]') -notmatch '^(y|yes)$') { Write-Host 'Cancelled.'; return }
[IO.Directory]::CreateDirectory($vault) | Out-Null
$created = (Get-Date).ToString('yyyy-MM-ddTHH:mm:sszzz')
function Save-Note([string]$relative, [string]$content) {
  $path = Join-Path $vault $relative
  [IO.Directory]::CreateDirectory((Split-Path $path -Parent)) | Out-Null
  [IO.File]::WriteAllText($path, $content, (New-Object Text.UTF8Encoding($false)))
}
